CREATE TABLE persona
(
    IDPER INT GENERATED BY DEFAULT ON NULL AS IDENTITY START WITH 200 INCREMENT BY 1,
    DENIPER CHAR(8),
    NOMPER VARCHAR2(60),
    APEPER VARCHAR2(80),
    EMAPER VARCHAR2(80),
    CELPER CHAR(9),
    TIPPER CHAR(1),
    ESTPER CHAR(1) DEFAULT 'A',
    FECNACPER DATE,
    CONSTRAINT PER_PK PRIMARY KEY (IDPER)
);
COMMIT;

CREATE TABLE venta
(
    IDVEN INT GENERATED BY DEFAULT ON NULL AS IDENTITY START WITH 200 INCREMENT BY 1,
    FECVEN DATE,
    IDCLI INT,
    IDVEND INT,
    TIPPAGVEN CHAR(1),
    ESTVEN CHAR (1),
    CONSTRAINT VEN_PK PRIMARY KEY (IDVEN)
);
COMMIT;

CREATE TABLE venta_detalle
(
    IDVENDET INT GENERATED BY DEFAULT ON NULL AS IDENTITY START WITH 200 INCREMENT BY 1,
    IDVEN INT,
    CODPROD CHAR(3),
    CANVENDET INT,
    CONSTRAINT VENDET_PK PRIMARY KEY (IDVENDET)
);
COMMIT;

DROP TABLE producto;

CREATE TABLE producto
(
    CODPROD CHAR(3),
    NOMPRO VARCHAR2(50),
    IDCAT INT,
    PREPRO NUMBER(8,2),
    STOCKPRO INT,
    ESTPRO CHAR(1),
    CONSTRAINT PROD_PK PRIMARY KEY (CODPROD)
);
COMMIT;

CREATE TABLE categoria
(
    IDCAT INT GENERATED BY DEFAULT ON NULL AS IDENTITY START WITH 200 INCREMENT BY 1,
    NOMCAT VARCHAR2(60),
    CONSTRAINT CAT_PK PRIMARY KEY (IDCAT)
);
COMMIT;

ALTER TABLE venta
    ADD CONSTRAINT persona_venta_fk FOREIGN KEY (IDCLI)
    REFERENCES persona (IDPER);
COMMIT;

ALTER TABLE venta_detalle
    ADD CONSTRAINT venta_venta_detalle_fk FOREIGN KEY (IDVEN)
    REFERENCES venta (IDVEN);
COMMIT;

ALTER TABLE venta_detalle
    ADD CONSTRAINT producto_venta_detalle_fk FOREIGN KEY (CODPROD)
    REFERENCES producto (CODPROD);
COMMIT;

ALTER TABLE producto
    ADD CONSTRAINT categoria_producto_fk FOREIGN KEY (IDCAT)
    REFERENCES categoria (IDCAT);
COMMIT;